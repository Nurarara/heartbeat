import assert from 'node:assert/strict';
import { DEFAULT_PROFILE, LONDON, previewFrame, localParts, decide, playbackProfile } from '../lib/world.ts';
import { playbackAction } from '../lib/playback.ts';
assert.equal(localParts(LONDON, Date.parse('2026-10-25T00:30:00Z')).hour, 1);
assert.equal(localParts(LONDON, Date.parse('2026-10-25T01:30:00Z')).hour, 1);
const midnight = new Intl.DateTimeFormat('en-GB', { timeZone: 'Asia/Kolkata', day:'numeric' }).format(Date.parse('2026-10-01T19:00:00Z'));
assert.equal(midnight, '2');
const now = Date.parse('2026-10-01T19:00:00Z');
const c = { temperature:12, observedAt:now, fetchedAt:now, weatherCode:3, isDay:false };
const f = { ...previewFrame(0,c,now), source:'live', generatedAt:now };
assert.equal(decide(DEFAULT_PROFILE,f,c,now+600000).action,'HOLD');
assert.equal(decide(DEFAULT_PROFILE,f,{...c,temperature:8},now+600000).action,'GENERATE');
assert.equal(decide(DEFAULT_PROFILE,f,{...c,stale:true},now+600000).action,'HOLD');
assert.equal(decide(DEFAULT_PROFILE,f,c,now,true).action,'GENERATE');
assert.equal(decide(DEFAULT_PROFILE,f,{...c,weatherCode:61},now+600000).action,'GENERATE');
assert.equal(decide(DEFAULT_PROFILE,f,c,now+10800001).action,'GENERATE');
assert.equal(new Set([previewFrame(0).url,previewFrame(1).url,previewFrame(2).url]).size,3);
const legacy = { ...DEFAULT_PROFILE, cadence:600, playbackVersion:undefined };
assert.equal(playbackProfile(legacy).cadence,600);
assert.equal(playbackProfile({...legacy,live:true}).cadence,600);
assert.equal(playbackProfile({...DEFAULT_PROFILE,cadence:600}).cadence,600);
assert.equal(playbackAction(30_000,30_000,true,false,false,false),'SWAP');
assert.equal(playbackAction(30_000,30_000,false,false,false,false),'PREPARE');
// Slow preparation and hidden-tab return do not start another whole interval.
assert.equal(playbackAction(43_000,30_000,true,false,false,false),'SWAP');
assert.equal(playbackAction(43_000,30_000,true,false,false,true),'WAIT');
assert.equal(playbackAction(43_000,30_000,true,false,true,false),'WAIT');
assert.equal(playbackAction(43_000,30_000,true,true,false,false),'WAIT');
assert.equal(playbackAction(43_000,30_000,false,false,false,false,45_000),'WAIT');
assert.equal(playbackAction(46_000,30_000,false,false,false,false,45_000),'PREPARE');
console.log('Passed timezone rollover, DST, hold/evolve policy, stale context, forced requests, and preview assets.');
