import assert from 'node:assert/strict';
import { DEFAULT_PROFILE, LONDON } from '../lib/world.ts';
import { interpretPulse, localPhase, weatherFamily } from '../lib/pulse.ts';
const profile={...DEFAULT_PROFILE,location:LONDON};
const morning=Date.parse('2026-10-02T08:00:00Z'),night=Date.parse('2026-10-02T22:00:00Z');
const observation=(at,temp=24,code=0)=>({temperature:temp,observedAt:at,fetchedAt:at,weatherCode:code,isDay:at<Date.parse('2026-10-02T17:45:00Z'),sunrise:'2026-10-02T06:45:00Z',sunset:'2026-10-02T17:45:00Z'});
const first=interpretPulse(profile,observation(morning),morning);
assert.equal(first.action,'REIMAGINE');assert.equal(first.environment.phase,'morning');
assert.equal(first.environment.phaseSource,'sun');assert.equal(first.environment.season,'autumn');
const stable=interpretPulse(profile,observation(morning+600000),morning+600000,first);
assert.equal(stable.action,'HOLD');assert.equal(stable.recentEvents.length,first.recentEvents.length);
const coldNight=interpretPulse(profile,observation(night,8,3),night,stable);
assert.equal(coldNight.action,'REIMAGINE');assert.equal(coldNight.environment.phase,'night');
assert.ok(coldNight.mood.energy<first.mood.energy);assert.ok(coldNight.mood.warmth>first.mood.warmth);
assert.ok(coldNight.effects.brightness<first.effects.brightness);assert.ok(coldNight.effects.driftSeconds>first.effects.driftSeconds);
const cloudy=interpretPulse(profile,observation(morning,24,2),morning);
assert.equal(interpretPulse(profile,observation(morning+600000,24,3),morning+600000,cloudy).action,'HOLD');
const rainy=interpretPulse(profile,observation(morning+600000,24,61),morning+600000,cloudy);
assert.equal(rainy.action,'REIMAGINE');assert.ok(rainy.mood.shelter>cloudy.mood.shelter);
assert.ok(rainy.instructions.some(x=>x.includes('only in exterior regions')));
const small=interpretPulse(profile,observation(morning+600000,22.4,0),morning+600000,first);
assert.equal(small.action,'ANIMATE');
const nearThreshold=interpretPulse(profile,observation(morning+600000,21.8,0),morning+600000,interpretPulse(profile,observation(morning,22.1),morning));
assert.equal(nearThreshold.environment.thermal,'warm');assert.equal(nearThreshold.action,'HOLD');
const stale=interpretPulse(profile,{...observation(morning,4,95),stale:true},morning,first);
assert.equal(stale.context,null);assert.equal(stale.environment.weather,'unknown');assert.notEqual(stale.action,'REIMAGINE');
assert.ok(stale.reason.includes('do not invent weather'));
assert.equal(localPhase(profile,observation(morning),Date.parse('2026-10-02T17:40:00Z')).phase,'dusk');
assert.equal(localPhase(profile,observation(morning),Date.parse('2026-10-02T18:30:00Z')).phase,'night');
const southern={...profile,location:{...LONDON,latitude:-33.86,timezone:'Australia/Sydney'}};
assert.equal(interpretPulse(southern,observation(morning),morning).environment.season,'spring');
const tropics={...profile,location:{...LONDON,latitude:12.97,timezone:'Asia/Kolkata'}};
assert.ok(interpretPulse(tropics,observation(morning),morning).environment.season.startsWith('tropical'));
assert.equal(weatherFamily(51),'rain');assert.equal(weatherFamily(75),'snow');assert.equal(weatherFamily(96),'storm');
assert.equal(interpretPulse(southern,observation(morning),morning,first).recentEvents.length,1);
console.log('Passed solar timing, temperature/time atmosphere, stable holds, small adjustments, weather families, hysteresis, stale-data protection, hemisphere seasons, and world isolation.');
