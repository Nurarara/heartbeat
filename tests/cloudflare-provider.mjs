import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { cloudflareProvider, ProviderFailure } from '../lib/ai/cloudflare.ts';
import { creativePacket } from '../lib/creative.ts';

const packet = creativePacket({ phase: 'night', season: 'autumn', temperature: 7, weekday: 'Thursday', festive: false }, undefined, 42, Date.now(), []);
const direction = { action: 'REIMAGINE', title: 'Quiet stars', reason: 'A dark screen suits the evening.', prompt: 'A restrained dark star field with faint points of light.', lighting: 'dark', themeIds: [] };
const config = { accountId: 'a'.repeat(32), apiToken: 'test-only-placeholder', directorModel: '@cf/test/text', imageModel: '@cf/black-forest-labs/flux-1-schnell' };
const calls = [];
let result = { response: direction }, status = 200, success = true, code;
const mock = async (url, options) => { calls.push({ url, ...options }); return Response.json({ success, result, errors: code ? [{ code }] : [] }, { status }); };
const provider = cloudflareProvider(config, mock);
assert.deepEqual(await provider.direct(packet), direction);
const sent = JSON.parse(calls[0].body);
assert.equal(sent.stream, false);
assert.deepEqual(sent.response_format, { type: 'json_object' });
assert.match(sent.messages[0].content, /"required":\["action","title","reason","prompt","lighting","themeIds"\]/);
assert.equal(sent.messages.length, 2);
assert.doesNotMatch(sent.messages[1].content, /test-only-placeholder/);
assert.equal(calls[0].headers.Authorization, 'Bearer test-only-placeholder');
result = { response: JSON.stringify(direction) };
assert.deepEqual(await provider.direct(packet), direction);
result = { response: { ...direction, lighting: 'daylight' } };
await assert.rejects(provider.direct(packet), error => error instanceof ProviderFailure && error.kind === 'invalid-output');
result = { response: { ...direction, unexpected: 'extra' } };
await assert.rejects(provider.direct(packet), error => error.kind === 'invalid-output');
result = { response: { ...direction, themeIds: ['unknown-theme'] } };
await assert.rejects(provider.direct(packet), error => error.kind === 'invalid-output');
result = { response: { ...direction, prompt: 'x'.repeat(1801) } };
await assert.rejects(provider.direct(packet), error => error.kind === 'invalid-output');
result = { response: { ...direction, action: 'HOLD', prompt: '', themeIds: [] } };
await assert.rejects(provider.direct(packet, { mustReimagine: true }), error => error.kind === 'invalid-output');
assert.match(JSON.parse(calls.at(-1).body).messages[0].content, /HOLD is not permitted/);
success = false; status = 429; code = 3036;
await assert.rejects(provider.direct(packet), error => error.kind === 'quota' && !error.retryable);
code = 3040;
await assert.rejects(provider.direct(packet), error => error.kind === 'capacity' && error.retryable);
status = 401; code = 9109;
await assert.rejects(provider.direct(packet), error => error.kind === 'configuration' && !error.retryable && error.status === 401 && error.code === 9109);
code = undefined;
status = 503;
await assert.rejects(provider.direct(packet), error => error.kind === 'upstream' && error.retryable);
success = true; status = 200;
result = { image: 'not a base64 image' };
await assert.rejects(provider.generate(direction, packet), error => error.kind === 'invalid-output');
const imageRequest = JSON.parse(calls.at(-1).body);
assert.deepEqual(Object.keys(imageRequest).sort(), ['prompt', 'steps']);
assert.match(imageRequest.prompt, /Near-black/);
const beforeHold = calls.length;
await assert.rejects(provider.generate({ ...direction, action: 'HOLD', prompt: '', themeIds: [] }, packet));
assert.equal(calls.length, beforeHold, 'A hold never calls image generation');
assert.throws(() => cloudflareProvider({ ...config, directorModel: '../../other-api' }, mock));
const oversize = cloudflareProvider(config, async () => new Response('x'.repeat(128001)));
await assert.rejects(oversize.direct(packet), error => error.kind === 'invalid-output');
const schemaFailure = cloudflareProvider(config, async () => Response.json({ success: false, errors: [{ code: 8007, message: 'JSON schema could not be met' }] }, { status: 400 }));
await assert.rejects(schemaFailure.direct(packet), error => error.kind === 'invalid-output' && error.code === 8007);
result={image:(await readFile('public/showcase/orchard.jpg')).toString('base64')};
await assert.rejects(provider.generate(direction,packet),error=>error.kind==='invalid-output'&&error.hints.includes('night-light'));
result={image:(await readFile('public/showcase/harbour.jpg')).toString('base64')};
assert.equal((await provider.generate(direction,packet)).width,1024);
console.log('Passed mocked Cloudflare request/response contracts, JSON variants, dark-scene validation, hold/no image call, error classification, output bounds and invalid image rejection. No live AI calls made.');
